    layout["barmode"] = "group"              # ← 柱狀模式：分組並排
    layout.update(
        yaxis=ax(showgrid=False, tickangle=0),   # ← Y軸不旋轉 (姓名)
        xaxis=ax(showgrid=True),                 # ← X軸顯示網格
    )
